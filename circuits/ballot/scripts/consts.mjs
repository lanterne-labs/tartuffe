#!/usr/bin/env node
// Writes src/consts.nr: the domain tags of SPEC §3 and the election public
// keys compiled into the ballot circuit (one circuit per key set).
//
//   node scripts/consts.mjs keys.txt > src/consts.nr
//
// keys.txt holds 2·J lines, x then y of each PK_j (the output of
// `nargo execute` in circuits/keygen). Tags are the ASCII strings
// "tartuffe-vote/2/<name>" read as big-endian integers.
import { readFileSync } from 'node:fs';

const J = 10;
const names = ['id', 'null', 'node', 'reg', 'prf', 'relay', 'dleq', 'nonce', 'pok', 'ct'];

const tag = (name) => {
	const bytes = Buffer.from(`tartuffe-vote/2/${name}`, 'ascii');
	if (bytes.length > 31) throw new Error(`tag too long: ${name}`);
	return BigInt('0x' + bytes.toString('hex'));
};

const file = process.argv[2];
if (!file) {
	console.error('usage: consts.mjs keys.txt');
	process.exit(2);
}
const lines = readFileSync(file, 'utf8')
	.split('\n')
	.map((l) => l.trim())
	.filter((l) => /^0x[0-9a-f]+$/i.test(l));
if (lines.length !== 2 * J) throw new Error(`expected ${2 * J} coordinates, got ${lines.length}`);

let out = '// Generated by scripts/consts.mjs. Do not edit.\n';
out += 'use std::embedded_curve_ops::EmbeddedCurvePoint;\n\n';
for (const n of names) out += `pub global T_${n.toUpperCase()}: Field = ${tag(n)};\n`;
out += `\n/// The election public keys PK_j = sk_j·G (SPEC §3).\npub global PK: [EmbeddedCurvePoint; ${J}] = [\n`;
for (let j = 0; j < J; j++) {
	out += `    EmbeddedCurvePoint { x: ${lines[2 * j]}, y: ${lines[2 * j + 1]} },\n`;
}
out += '];\n';
process.stdout.write(out);
